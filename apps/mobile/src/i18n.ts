export const dictionaries = { en, ar };

export function translate(
  lang: Lang,
  key: TKey,
  vars?: Record<string, string | number>,
): string {
  const dictionary = lang === 'ar' ? ar : en;
  let value = dictionary[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function formatDistance(metres: number, lang: Lang): string {
  if (metres < 1000) {
    return `${Math.max(0, Math.round(metres))} ${lang === 'ar' ? 'م' : 'm'}`;
  }
  return `${(metres / 1000).toFixed(1)} ${lang === 'ar' ? 'كم' : 'km'}`;
}

export function formatDuration(seconds: number, lang: Lang): string {
  const minutes = Math.max(1, Math.round(seconds / 60));
  return `${minutes} ${lang === 'ar' ? 'د' : 'min'}`;
}
